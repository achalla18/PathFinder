"""The sidewalk mapping worklist: OSM streets inside the region's line with no sidewalk evidence,
longest first, grouped into areas a mapper can cover in one session.

Criterion 3 counts a street once anything records whether it has a sidewalk, "no" included, so
tagging ``sidewalk=*`` on an OSM street adds its whole length. One row per OSM way, because a tag
goes on the whole way. Service roads, alleys and freeways are left out: they would lift the number without helping
anyone walk.

    python tools/sidewalk_mapping/make_worklist.py    # reports/<region>/sidewalk_mapping/

Internal: which streets lack evidence depends on the City of Frederick's survey (rule 7). The
worklist only says where to look; what goes into OSM must come from what mappers see
(field/sidewalk_mapping.md).
"""
from __future__ import annotations

import sys

import geopandas as gpd
import numpy as np
import pandas as pd

from pathfinder.analysis.coverage import BAR, accessibility_bar
from pathfinder.config import GRAPH_DIR, REPORTS_DIR, WGS84
from pathfinder.sources import REGION

OUT = REPORTS_DIR / "sidewalk_mapping"
AREA_M = 800.0  # an area is an 800 m grid square: a neighbourhood, about an hour on foot or on screen
STREET_KINDS = ("street_unknown", "street_with_sidewalk", "street_no_sidewalk", "pedestrian_street")
# Freeways and their ramps: nobody walks along them, so a sidewalk tag there helps no one
# (Catoctin Mountain Highway, US 15, was on the first worklist).
NOT_WALKED = ("motorway", "motorway_link", "trunk", "trunk_link")


def main() -> None:
    full = gpd.read_parquet(GRAPH_DIR / "edges.parquet")
    e = full[~full["outside_region"].astype(bool) & full["representation"].eq("street_centerline")
             & full["kind"].isin(STREET_KINDS) & full["sidewalk_presence_status"].eq("unknown")
             & ~full["highway"].isin(NOT_WALKED)]
    g = e.groupby("osm_way_id")
    ways = pd.DataFrame({"unknown_m": g["length_m"].sum(), "name": g["name"].first(), "highway": g["highway"].first()})
    geom = gpd.GeoSeries(g.apply(lambda d: d.geometry.union_all(), include_groups=False), crs=e.crs)
    mid = geom.apply(lambda x: x.interpolate(0.5, normalized=True) if x.geom_type == "LineString" else x.representative_point())
    ways["area"] = [f"{int(p.x // AREA_M)}_{int(p.y // AREA_M)}" for p in mid]
    ll = gpd.GeoSeries(mid, crs=e.crs).to_crs(WGS84)
    ways["lat"], ways["lon"] = ll.y.round(6), ll.x.round(6)

    # areas by the length they would add; within an area, the longest ways first
    by_area = ways.groupby("area")["unknown_m"].sum().sort_values(ascending=False)
    area_rank = {a: i + 1 for i, a in enumerate(by_area.index)}
    ways["area_rank"] = ways["area"].map(area_rank)
    ways = ways.sort_values(["area_rank", "unknown_m"], ascending=[True, False]).reset_index()
    stats = {"largest_component_share_of_length": float("nan")}
    now = accessibility_bar(full, stats)[2]
    walkable_km = full.loc[~full["outside_region"].astype(bool), "length_m"].sum() / 1000
    need_km = max(0.0, (BAR["sidewalk_evidence"] - now["value_pct"]) / 100 * walkable_km)
    ways["cumulative_km"] = (ways["unknown_m"].cumsum() / 1000).round(2)
    ways["edit"] = "https://www.openstreetmap.org/edit?editor=id&way=" + ways["osm_way_id"].astype(str)
    ways["photos"] = [f"https://www.mapillary.com/app/?lat={a}&lng={o}&z=18" for a, o in zip(ways["lat"], ways["lon"])]
    ways["unknown_m"] = ways["unknown_m"].round(0).astype(int)
    cols = ["area_rank", "osm_way_id", "name", "highway", "unknown_m", "cumulative_km", "lat", "lon", "edit", "photos"]
    OUT.mkdir(parents=True, exist_ok=True)
    ways[cols].to_csv(OUT / "worklist.csv", index=False)

    areas = ways.groupby("area_rank").agg(km=("unknown_m", lambda s: s.sum() / 1000), ways=("osm_way_id", "size"),
                                         lat=("lat", "mean"), lon=("lon", "mean"),
                                         streets=("name", lambda s: ", ".join(s.dropna().value_counts().index[:3])))
    areas["cumulative_km"] = areas["km"].cumsum()
    n_bar = int((areas["cumulative_km"] < need_km).sum()) + 1 if need_km else 0
    md = [f"# Sidewalk mapping worklist ({REGION.name})", "",
          "_Generated by `tools/sidewalk_mapping/make_worklist.py`. Do not edit by hand. **Internal:** which streets lack "
          "evidence depends on the City of Frederick's survey (rule 7). How to map: `field/sidewalk_mapping.md`._", "",
          f"Criterion 3 (sidewalk evidence) is {now['value_pct']}% against a {BAR['sidewalk_evidence']:.0f}% bar: "
          f"**{need_km:.1f} km** of street to record. {len(ways):,} OSM streets inside the line, "
          f"{ways['unknown_m'].sum() / 1000:.1f} km, have no sidewalk evidence (service roads, alleys and freeways left out). "
          f"The first **{n_bar} areas** below hold enough.", "",
          f"Every way, with its edit and photo links: [`worklist.csv`](worklist.csv).", "",
          "| area | km | ways | main streets | cumulative km | map |", "|---|---|---|---|---|---|",
          *[f"| {i} | {r.km:.1f} | {r.ways} | {r.streets or '(unnamed)'} | {r.cumulative_km:.1f} | "
            f"[open](https://www.openstreetmap.org/edit?editor=id#map=17/{r.lat:.5f}/{r.lon:.5f}) |"
            for i, r in areas.head(max(n_bar + 5, 15)).iterrows()], ""]
    (OUT / "README.md").write_text("\n".join(md), encoding="utf-8")
    sys.stdout.reconfigure(encoding="utf-8")
    print("\n".join(md[:6]))


if __name__ == "__main__":
    main()
